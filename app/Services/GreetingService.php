    ];

    private const SHORT_MESSAGES = [
        'morning'   => [
            'صبح بخیر {name} ☀️',
            'سلام {name}، روز بخیر 🌅',
            'وقت بخیر {name} ☕',
        ],
        'afternoon' => [
            'ظهر بخیر {name} ☀️',
            'نیمروز بخیر {name} 🍃',
            'خسته نباشی {name} 🚀',
        ],
        'evening'   => [
            'عصر بخیر {name} 🌇',
            'عصرت بخیر {name} ☕',
            'سلام {name} عزیز 🌆',
        ],
        'night'     => [
            'شب بخیر {name} 🌙',
            'شبت آرام {name} ✨',
            'سلام {name}، شب بخیر 🌌',
        ],
    ];

    public function getGreeting(): string
    {
        $key      = $this->getTimeOfDay() . '_' . $this->getDayOfWeek();
        $messages = self::MESSAGES[$key];

        return $messages[array_rand($messages)];
    }

    public function getShortGreeting(string $name): string
    {
        $key      = $this->getTimeOfDay();
        $messages = self::SHORT_MESSAGES[$key];

        return str_replace('{name}', $name, $messages[array_rand($messages)]);
    }

    private function getTimeOfDay(): string
    {
        $hour = (int) Carbon::now()->format('H');
        return match(true) {
            $hour >= 5  && $hour < 12 => 'morning',
            $hour >= 12 && $hour < 17 => 'afternoon',
            $hour >= 17 && $hour < 21 => 'evening',
            default                   => 'night',
        };
    }

    private function getDayOfWeek(): string
    {
        return match((int) Carbon::now()->dayOfWeek) {
            Carbon::SATURDAY  => 'saturday',
            Carbon::SUNDAY    => 'sunday',
            Carbon::MONDAY    => 'monday',
            Carbon::TUESDAY   => 'tuesday',
            Carbon::WEDNESDAY => 'wednesday',
            Carbon::THURSDAY  => 'thursday',
            Carbon::FRIDAY    => 'friday',
        };
    }
